export async function POST(request: NextRequest) {
  try {
    const { chapterId } = await request.json();
    
    if (!chapterId || !chapterTexts[chapterId]) {
      return NextResponse.json({ error: '无效的章节ID' }, { status: 400 });
    }

    const text = chapterTexts[chapterId];
    const customHeaders = HeaderUtils.extractForwardHeaders(request.headers);
    
    const config = new Config();
    const client = new TTSClient(config, customHeaders);
    
    // 使用适合培训讲解的声音
    const response = await client.synthesize({
      uid: `training-chapter-${chapterId}`,
      text: text,
      speaker: 'zh_female_xueayi_saturn_bigtts', // 儿童有声书风格，亲切易懂
      audioFormat: 'mp3',
      sampleRate: 24000,
      speechRate: 0, // 正常语速
      loudnessRate: 10 // 稍大声一点
    });

    console.log(`[TTS] 章节${chapterId}音频生成成功: ${response.audioUri}`);

    return NextResponse.json({ 
      audioUrl: response.audioUri,
      audioSize: response.audioSize 
    });
  } catch (error) {
    console.error('[TTS] 生成失败:', error);
    return NextResponse.json({ 
      error: error instanceof Error ? error.message : '音频生成失败' 
    }, { status: 500 });
  }
}
